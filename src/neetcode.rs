#[cfg(test)]
mod tests {
    use super::NEETCODE_250;
    use std::collections::HashSet;

    #[test]
    fn holds_250_distinct_slugs() {
        assert_eq!(NEETCODE_250.len(), 250);
        let unique: HashSet<_> = NEETCODE_250.iter().collect();
        assert_eq!(unique.len(), 250);
    }

    #[test]
    fn matches_neet250_json() {
        let json: serde_json::Value =
            serde_json::from_str(include_str!("../neet250.json")).unwrap();
        let from_json: Vec<&str> = json
            .as_object()
            .unwrap()
            .values()
            .flat_map(|v| v.as_array().unwrap().iter().map(|s| s.as_str().unwrap()))
            .collect();
        // serde_json sorts object keys, so compare membership, not order.
        assert_eq!(from_json.len(), NEETCODE_250.len());
        let listed: HashSet<&str> = NEETCODE_250.iter().copied().collect();
        assert!(from_json.iter().all(|s| listed.contains(s)));
    }
}
